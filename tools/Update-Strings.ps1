<#
.SYNOPSIS
    Turns tools\strings\*.txt into the .resx files the app embeds and the Strings accessor it calls.

.DESCRIPTION
    en.txt is the source of truth: every key in it becomes a property on AntiPilot.Strings, so a
    typo in calling code is a compile error rather than a blank label at runtime. Each other
    <tag>.txt is a translation and needs only the keys it actually translates — ResourceManager
    falls back to the neutral (English) resource for the rest.

    Run this after editing any file under tools\strings.
#>
[CmdletBinding()]
param(
    [string]$StringsDir = (Join-Path $PSScriptRoot 'strings'),
    [string]$ResourceDir = (Join-Path $PSScriptRoot '..\src\AntiPilot\Resources'),
    [string]$AccessorPath = (Join-Path $PSScriptRoot '..\src\AntiPilot\Strings.g.cs'),

    # Fails instead of writing when a translation carries a key English does not have, or when a
    # format string has lost a placeholder. Used by CI.
    [switch]$CheckOnly
)

$ErrorActionPreference = 'Stop'

function Read-StringTable([string]$path) {
    $table = [ordered]@{}
    $lineNumber = 0

    foreach ($line in Get-Content -LiteralPath $path -Encoding UTF8) {
        $lineNumber++
        $trimmed = $line.Trim()
        if ($trimmed.Length -eq 0 -or $trimmed.StartsWith('#')) { continue }

        $split = $trimmed.IndexOf('=')
        if ($split -lt 1) { throw "${path}:${lineNumber}: expected 'Key = value'." }

        $key = $trimmed.Substring(0, $split).Trim()
        $value = $trimmed.Substring($split + 1).Trim()

        if ($table.Contains($key)) { throw "${path}:${lineNumber}: duplicate key '$key'." }
        $table[$key] = $value -replace '\\n', "`n"
    }

    return $table
}

# The placeholders a string uses, so a translation cannot quietly drop one and crash string.Format.
function Get-Placeholders([string]$value) {
    [regex]::Matches($value, '\{(\d+)\}') | ForEach-Object { [int]$_.Groups[1].Value } | Sort-Object -Unique
}

