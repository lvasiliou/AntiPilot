function Write-Resx([string]$path, $table, [string]$sourceName) {
    $builder = [Text.StringBuilder]::new()
    [void]$builder.AppendLine($resxHeader)
    [void]$builder.AppendLine("  <!-- Generated by tools\Update-Strings.ps1 from tools\strings\$sourceName. Do not edit. -->")

    foreach ($key in $table.Keys) {
        $escaped = [Security.SecurityElement]::Escape($table[$key])
        [void]$builder.AppendLine("  <data name=""$key"" xml:space=""preserve"">")
        [void]$builder.AppendLine("    <value>$escaped</value>")
        [void]$builder.AppendLine('  </data>')
    }

    [void]$builder.AppendLine('</root>')

    $text = $builder.ToString() -replace "`r`n", "`n" -replace "`n", "`r`n"
    if ($CheckOnly) { return }
    New-Item -ItemType Directory -Force -Path (Split-Path -Parent $path) | Out-Null
    [IO.File]::WriteAllText($path, $text, [Text.UTF8Encoding]::new($false))
}

$englishPath = Join-Path $StringsDir 'en.txt'
if (-not (Test-Path -LiteralPath $englishPath)) { throw "Missing $englishPath." }
$english = Read-StringTable $englishPath
Write-Host "en.txt: $($english.Count) strings" -ForegroundColor Cyan

$problems = [Collections.Generic.List[string]]::new()
$translations = Get-ChildItem -LiteralPath $StringsDir -Filter '*.txt' |
    Where-Object { $_.Name -ne 'en.txt' } | Sort-Object Name

foreach ($file in $translations) {
    $tag = [IO.Path]::GetFileNameWithoutExtension($file.Name)
    $table = Read-StringTable $file.FullName

    foreach ($key in $table.Keys) {
        if (-not $english.Contains($key)) {
            $problems.Add("$($file.Name): key '$key' does not exist in en.txt.")
            continue
        }

        $wanted = @(Get-Placeholders $english[$key])
        $got = @(Get-Placeholders $table[$key])
        if (Compare-Object $wanted $got) {
            $problems.Add("$($file.Name): '$key' uses placeholders {$($got -join ',')} but English uses {$($wanted -join ',')}.")
        }
    }

    $missing = @($english.Keys | Where-Object { -not $table.Contains($_) })
    $coverage = [math]::Round(($english.Count - $missing.Count) / $english.Count * 100)
    Write-Host ("{0,-8} {1,3}/{2} translated ({3}%)" -f $tag, ($english.Count - $missing.Count), $english.Count, $coverage)

    Write-Resx (Join-Path $ResourceDir "Strings.$tag.resx") $table $file.Name
}

if ($problems.Count -gt 0) {
    $problems | ForEach-Object { Write-Host "  $_" -ForegroundColor Red }
    throw "$($problems.Count) problem(s) in the string tables."
}

Write-Resx (Join-Path $ResourceDir 'Strings.resx') $english 'en.txt'

# ---- the accessor -----------------------------------------------------------

$accessor = [Text.StringBuilder]::new()
[void]$accessor.AppendLine(@'
// <auto-generated>
//     Generated by tools\Update-Strings.ps1 from tools\strings\en.txt. Do not edit.
// </auto-generated>

#nullable enable

using System.Globalization;
using System.Resources;

namespace AntiPilot;

/// <summary>
/// Every user-visible string in the app. English lives in Resources\Strings.resx and is compiled
/// into the executable, so a missing translation degrades to English rather than to a blank label.
/// </summary>
public static partial class Strings
{
    private static readonly ResourceManager Resources =
        new("AntiPilot.Resources.Strings", typeof(Strings).Assembly);

    /// <summary>
    /// The language to look strings up in. Null follows Windows. Set once at start-up from
    /// <see cref="AppConfig.Language"/>; changing it later does not relabel windows already open.
    /// </summary>
    public static CultureInfo? Culture { get; set; }

    /// <summary>Looks up one string. Never throws: a missing key shows as !Key! instead.</summary>
    public static string Get(string key)
    {
        try
        {
            return Resources.GetString(key, Culture) ?? $"!{key}!";
        }
        catch (Exception)
        {
            return $"!{key}!";
        }
    }

    /// <summary>Shorthand for a string that carries {0}-style placeholders.</summary>
    public static string Format(string value, params object?[] arguments) =>
        string.Format(Culture ?? CultureInfo.CurrentUICulture, value, arguments);
'@)

foreach ($key in $english.Keys) {
    $comment = $english[$key] -replace "`n", ' '
    if ($comment.Length -gt 96) { $comment = $comment.Substring(0, 93) + '...' }
    [void]$accessor.AppendLine()
    [void]$accessor.AppendLine("    /// <summary>$([Security.SecurityElement]::Escape($comment))</summary>")
    [void]$accessor.AppendLine("    public static string $key => Get(""$key"");")
}

[void]$accessor.AppendLine('}')

if (-not $CheckOnly) {
    $text = $accessor.ToString() -replace "`r`n", "`n" -replace "`n", "`r`n"
    [IO.File]::WriteAllText($AccessorPath, $text, [Text.UTF8Encoding]::new($false))
}

$verb = if ($CheckOnly) { 'Checked' } else { 'Wrote' }
Write-Host "$verb $($english.Count) strings, $($translations.Count) translation(s)." -ForegroundColor Green
